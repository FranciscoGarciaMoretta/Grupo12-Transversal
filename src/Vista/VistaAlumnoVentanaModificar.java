    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        try {

            String nombre = txtNombre.getText();
            int dni = Integer.parseInt(txtDni.getText());

            DateTimeFormatter formateador = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate fechaNac = LocalDate.parse(txtFechaNac.getText(), formateador);

            alumnoSeleccionado.setNombre(nombre);
            alumnoSeleccionado.setDni(dni);
            alumnoSeleccionado.setFecNac(fechaNac);

            AlumnoData alumnoData = new AlumnoData();
            alumnoData.update(alumnoSeleccionado);

            JOptionPane.showMessageDialog(this, "Alumno actualizado correctamente en la base de datos.");
            if (this.vistaAlumno != null) {
                this.vistaAlumno.updateTable();
            }
            this.dispose();

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use dd/MM/yyyy.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnConfirmarActionPerformed

