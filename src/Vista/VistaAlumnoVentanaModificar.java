private void cargarDatos() {
        txtDni.setText(String.valueOf(alumnoSeleccionado.getDni()));
        txtNombre.setText(alumnoSeleccionado.getNombre());

        LocalDate fechaNac = alumnoSeleccionado.getFecNac();
        if (fechaNac != null) {
            // 2. Definir el formato deseado (Día/Mes/Año)
            DateTimeFormatter formateador = DateTimeFormatter.ofPattern("dd/MM/yyyy");

            // 3. Convertir el LocalDate a String usando el formato
            String fechaEnTexto = fechaNac.format(formateador);

            // 4. Asignar el texto a tu campo de la interfaz
            txtFechaNac.setText(fechaEnTexto);
        } else {
            txtFechaNac.setText("");
        }

    }

